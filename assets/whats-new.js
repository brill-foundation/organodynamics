"use strict";
/* What's new — the review-marker system.

   A quiet "there is something new to discover here." It is a Camera: it reveals
   real change and invents nothing. Each Place of the Space carries a content
   token (assets/whats-new.json, generated by tools/whats-new.js from the Place's
   own bytes). We remember, per visitor, the token last seen; on first encounter
   that memory is seeded to the production (main) baseline — so a marker means
   exactly "work you have not looked at yet, since the version you last reviewed."

   Rules honoured:
     · one marker per Place, however much changed inside it;
     · a marker clears the moment you open (or land on) that Place;
     · genuinely new Places may carry a small "New" badge instead of a dot;
     · nothing is explained, counted, ranked, or authored — only revealed.

   An element opts in with data-area="<place-key>" (rail stops, entry cards, the
   top-nav links). Provenance is exposed at window.__WHATSNEW__ so any marker is
   answerable. Zero dependencies; works offline and from a bare folder. */
(function () {
  var KEY = "brill:whats-new:v1";
  var here = (document.body && document.body.dataset && document.body.dataset.place) || "";
  // a page's data-place → the Place key it marks seen by being visited
  var PLACE_AREA = {
    brill: "", threshold: "threshold", laboratory: "laboratory",
    constitution: "constitution", rfcs: "rfcs", cabinet: "cabinet", sessions: "sessions"
  };

  function load() { try { return JSON.parse(localStorage.getItem(KEY)); } catch (e) { return null; } }
  function save(s) { try { localStorage.setItem(KEY, JSON.stringify(s)); } catch (e) {} }
  function isHe() { return ((window.LAB_LANG && window.LAB_LANG.current) || document.documentElement.lang || "en").slice(0, 2) === "he"; }

  fetch("/assets/whats-new.json", { cache: "no-store" })
    .then(function (r) { return r.ok ? r.json() : null; })
    .then(function (man) {
      if (!man || !man.areas) return;
      var areas = man.areas;

      var store = load();
      if (!store || store.v !== 1) {
        // First encounter: baseline the visitor's memory to the last production
        // state, so accumulated-since-production work reveals itself once, then
        // tracks incrementally. Honest: the baseline is the version they last saw.
        var seen = {};
        Object.keys(areas).forEach(function (k) { seen[k] = areas[k].baseline || ""; });
        store = { v: 1, seen: seen };
        save(store);
      }

      function changed(k) { return areas[k] && (store.seen[k] || "") !== (areas[k].token || ""); }

      // Provenance ledger — every marker must be traceable to evidence.
      var changedList = Object.keys(areas).filter(changed);
      window.__WHATSNEW__ = {
        generatedAt: man.generatedAt, base: man.base,
        changed: changedList, areas: areas,
        why: "A Place is marked iff its current content token differs from the token you last saw (seeded to the main baseline on first visit)."
      };

      function tip() { return isHe() ? "חדש מאז הביקור האחרון שלך" : "new since your last visit"; }

      function markSeen(k) {
        if (!areas[k]) return;
        store.seen[k] = areas[k].token || "";
        save(store);
        // Markers are attributes, not nodes — clearing is just removing them.
        document.querySelectorAll('[data-area="' + k + '"][data-wn]').forEach(function (el) {
          el.removeAttribute("data-wn");
          el.removeAttribute("title");
        });
      }

      // Landing on a Place's own page counts as seeing it.
      var hereArea = PLACE_AREA[here];
      if (hereArea && areas[hereArea]) markSeen(hereArea);

      function decorate(el) {
        var k = el.getAttribute("data-area");
        if (!k || !changed(k) || el.hasAttribute("data-wn")) return;
        var isRoom = el.classList.contains("room");
        var neverSeen = (store.seen[k] || "") === "";
        // A genuinely-new Place shows the "New" badge in inline contexts (nav,
        // rail); cards take the quiet corner dot so nothing overlaps the tile.
        var kind = isRoom ? "corner" : (areas[k].new && neverSeen ? "new" : "dot");
        el.setAttribute("data-wn", kind);
        el.setAttribute("title", tip());
      }

      function render() {
        document.querySelectorAll("[data-area]").forEach(decorate);
        // Following a link into a Place clears its marker optimistically.
        document.querySelectorAll('a[data-area]').forEach(function (a) {
          a.addEventListener("click", function () { markSeen(a.getAttribute("data-area")); }, { once: true });
        });
        // Keep the tooltip language in step on toggle (the badge text is CSS-driven).
        var btn = document.getElementById("langToggle");
        if (btn) btn.addEventListener("click", function () {
          document.querySelectorAll('[data-wn][title]').forEach(function (el) { el.setAttribute("title", tip()); });
        });
      }

      if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", render);
      else render();
    })
    .catch(function () { /* offline or bare folder without the manifest — no markers, no error */ });
})();
